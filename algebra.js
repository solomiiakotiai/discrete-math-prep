let alSimSec = 420, alSimTimer = null;
function alFormatTime(s) { return String(Math.floor(s / 60)).padStart(2, '0') + ':' + String(s % 60).padStart(2, '0'); }
function alStartSim() {
  const btn = document.getElementById('al-sim-btn');
  const timerEl = document.getElementById('al-sim-timer');
  const holder = document.getElementById('al-sim-ticket');
  if (alSimTimer) {
    clearInterval(alSimTimer); alSimTimer = null;
    btn.textContent = 'Продовжити симуляцію';
    return;
  }
  if (alSimSec === 0) { alSimSec = 420; timerEl.textContent = '07:00'; holder.innerHTML = ''; }
  if (alSimSec === 420 && !holder.querySelector('.ticket-card')) {
    const k = Math.floor(Math.random() * 100) + 1;
    const slots = alSlots(k);
    const items = slots.map(s => {
      const item = alFind(s.nivel, s.qNum);
      return '<li style="margin-bottom:10px"><span class="tag">Nivel ' + s.nivel + ' · №' + s.qNum + '</span> <b>' + item.title + '</b>' +
        '<details style="margin-top:6px"><summary>Показати ' + (s.nivel === 1 ? 'означення' : s.nivel === 2 ? 'розв’язок' : 'доведення') + '</summary>' +
        '<div class="proof-box" style="margin-top:8px">' + alBody(item, k) + '</div></details></li>';
    }).join('');
    holder.innerHTML = '<div class="panel ticket-card"><span class="tag">Тренувальний білет №' + k + '</span>' +
      '<h3>Відповідай на 6 питань білета</h3>' +
      '<p class="helper">Спершу спробуй відповісти самостійно (письмово чи усно). Коли час вийде — розкривай відповіді нижче й звіряйся. Усі формули питань — як у справжньому білеті: ' + slots.map(s => s.formula).join('; ') + '.</p>' +
      '<ol style="padding-left:20px;margin:14px 0 0">' + items + '</ol></div>';
  }
  btn.textContent = 'Пауза';
  alSimTimer = setInterval(() => {
    alSimSec = Math.max(0, alSimSec - 1);
    timerEl.textContent = alFormatTime(alSimSec);
    if (alSimSec === 0) {
      clearInterval(alSimTimer); alSimTimer = null;
      btn.textContent = 'Почати знову';
      holder.insertAdjacentHTML('beforeend', '<p class="helper" style="text-align:center;margin-top:12px">Час! Порівняй свої відповіді з готовими розв’язками.</p>');
    }
  }, 1000);
}

