/* ---------- допоміжні функції ---------- */
function alMod(a, b) { const r = a % b; return r === 0 ? b : r; }
function alGcd(a, b) { a = Math.abs(a); b = Math.abs(b); while (b) { [a, b] = [b, a % b]; } return a; }
function alFrac(n, d) {
  if (d === undefined) d = 1;
  if (d < 0) { n = -n; d = -d; }
  const g = alGcd(n, d) || 1;
  return [n / g, d / g];
}
function alFs(f) {
  const n = f[0], d = f[1];
  const s = (d === 1) ? String(Math.abs(n)) : Math.abs(n) + '/' + d;
  return (n < 0 ? '−' : '') + s;
}
function alNum(n) { return n < 0 ? '−' + Math.abs(n) : String(n); }
function alMatMul(A, B) {
  return A.map((row, i) => B[0].map((_, j) => row.reduce((s, _x, k) => s + A[i][k] * B[k][j], 0)));
}
/* матриця в моноширинному блоці */
function alMatBlock(M, fmt) {
  fmt = fmt || alNum;
  const cells = M.map(r => r.map(fmt));
  const w = Math.max.apply(null, cells.map(r => Math.max.apply(null, r.map(s => s.length))));
  const lines = cells.map(r => '( ' + r.map(s => s.padStart(w, ' ')).join('  ') + ' )');
  return '<div class="code" style="white-space:pre;overflow-x:auto">' + lines.join('\n') + '</div>';
}

