/* список питань */
function alToggleProof(btn) {
  const card = btn.closest('.question-item-card');
  if (!card) return;
  const box = card.querySelector('.question-proof-content');
  if (!box) return;
  if (box.hidden && box.getAttribute('data-dynamic') === '1') {
    const kField = document.getElementById('al-k-val');
    const k = Math.min(100, Math.max(1, Number(kField && kField.value) || 1));
    const item = alFind(Number(card.getAttribute('data-nivel')), Number(card.getAttribute('data-num')));
    box.innerHTML = '<i>Розв’язок для k = ' + k + ' (значення береться з поля «Розрахуй варіант k» на сторінці білета).</i><br><br>' + alBody(item, k);
  }
  const wasHidden = box.hidden;
  box.hidden = !wasHidden;
  btn.classList.toggle('active', wasHidden);
  btn.setAttribute('aria-expanded', String(wasHidden));
  const arrow = btn.querySelector('.proof-arrow');
  if (arrow) arrow.textContent = wasHidden ? '↑' : '↓';
}

